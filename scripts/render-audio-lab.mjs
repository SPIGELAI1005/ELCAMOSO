/**
 * Headless Prompt 01 lab captures through the production SoundEngine.
 *
 * Usage:
 *   npm run audio:lab
 *   AUDIO_LAB_PROFILES=gt-v8,cyber-pulse AUDIO_LAB_FIXTURES=idle,gentle-0-80 npm run audio:lab
 *   AUDIO_LAB_OUT=artifacts/audio-lab/local npm run audio:lab
 *
 * Does not fabricate listening results. Writes WAV + metadata JSON + pending baseline reports.
 */
import { chromium } from "@playwright/test";
import { mkdir, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { createServer } from "vite";

const envList = (name) =>
  (process.env[name] ?? "")
    .split(",")
    .map((value) => value.trim())
    .filter(Boolean);

const outputDir = path.resolve(
  process.env.AUDIO_LAB_OUT ?? `artifacts/audio-lab/${new Date().toISOString().slice(0, 10)}`,
);
const requestedProfiles = envList("AUDIO_LAB_PROFILES");
const requestedFixtures = envList("AUDIO_LAB_FIXTURES");

const server = await createServer({ server: { host: "127.0.0.1", port: 0 } });
let browser;
try {
  await server.listen();
  const address = server.httpServer?.address();
  if (!address || typeof address === "string") throw new Error("Vite did not expose a TCP port");
  const origin = `http://127.0.0.1:${address.port}`;
  browser = await chromium.launch({ channel: "chrome", headless: true });
  const page = await browser.newPage();
  await page.goto(origin, { waitUntil: "domcontentloaded" });
  await mkdir(outputDir, { recursive: true });

  const catalog = await page.evaluate(async () => {
    const profiles = await import("/src/lib/sound/profiles.ts");
    const lab = await import("/src/lib/sound/lab/index.ts");
    return {
      profileIds: profiles.SOUND_PROFILES.map((profile) => profile.id),
      fixtures: lab.LAB_FIXTURES.map((fixture) => ({
        id: fixture.id,
        kind: fixture.kind,
      })),
      pendingReports: lab.allPendingBaselineReports(),
    };
  });

  const profileIds = requestedProfiles.length
    ? catalog.profileIds.filter((id) => requestedProfiles.includes(id))
    : catalog.profileIds;
  const fixtureIds = requestedFixtures.length
    ? catalog.fixtures.map((f) => f.id).filter((id) => requestedFixtures.includes(id))
    : catalog.fixtures.filter((f) => f.kind === "speed-driven").map((f) => f.id);

  await writeFile(
    path.join(outputDir, "baseline-reports-pending.json"),
    `${JSON.stringify(
      {
        generatedAt: new Date().toISOString(),
        note: "Measured metrics pending until captures below succeed. Do not treat this file as listening verification.",
        reports: catalog.pendingReports,
      },
      null,
      2,
    )}\n`,
  );

  const results = [];
  for (const profileId of profileIds) {
    for (const fixtureId of fixtureIds) {
      const result = await page.evaluate(
        async ({ profileId: id, fixtureId: fixture }) => {
          const lab = await import("/src/lib/sound/lab/index.ts");
          return lab.renderLabCapture({
            profileId: id,
            profileIdB: id === "gt-v8" ? "cyber-pulse" : "gt-v8",
            fixtureId: fixture,
            includeSpectrum: false,
          });
        },
        { profileId, fixtureId },
      );
      const wav = Buffer.from(result.wavBase64, "base64");
      delete result.wavBase64;
      const stem = `${profileId}__${fixtureId}`;
      await writeFile(path.join(outputDir, `${stem}.wav`), wav);
      await writeFile(
        path.join(outputDir, `${stem}.meta.json`),
        `${JSON.stringify(result.metadata, null, 2)}\n`,
      );
      results.push({
        profileId,
        fixtureId,
        metadata: result.metadata,
        metrics: result.metrics,
        renderElapsedMs: result.renderElapsedMs,
      });
      process.stdout.write(
        `${results.length} ${stem}: ${result.metadata.rendererBackend} / ${result.metadata.excitationMode ?? "n/a"}\n`,
      );
    }
  }

  await writeFile(
    path.join(outputDir, "analysis.json"),
    `${JSON.stringify(
      {
        generatedAt: new Date().toISOString(),
        harness: "Prompt 01 audio lab · production SoundEngine",
        hardware: {
          platform: `${os.platform()} ${os.release()} ${os.arch()}`,
          cpu: os.cpus()[0]?.model ?? "unknown",
          logicalCpuCount: os.cpus().length,
          totalMemoryBytes: os.totalmem(),
        },
        profileCount: profileIds.length,
        fixtureCount: fixtureIds.length,
        limitations: results[0]?.metadata.limitations ?? [],
        results,
      },
      null,
      2,
    )}\n`,
  );

  await writeFile(
    path.join(outputDir, "README.md"),
    `# Audio lab capture\n\nGenerated by \`npm run audio:lab\`.\n\n- Production SoundEngine offline captures\n- Metrics are sample peak/RMS and approximate loudness — not certified LUFS or true peak\n- Listening-verified: **no** (human assessment still required)\n`,
  );
} finally {
  await browser?.close();
  await server.close();
}
