/** Per-sound "fuel": what the imitated vehicle would really (or playfully) consume. */
export type FuelUnit = "L" | "kg" | "g" | "kWh" | { one: string; many: string };
export interface FuelSpec {
  name: string;
  emoji: string;
  unit: FuelUnit;
  /** amount per km at calm driving */
  perKm: number;
  /** "user" = use the fuel price from settings (per litre), else EUR per unit */
  priceEur: number | "user" | "user-kwh";
  /** kg CO2 per unit */
  co2: number;
  fun?: boolean;
  /** {a} is replaced with the formatted amount */
  quip: string;
}

const petrol = (lPer100: number, quip: string): FuelSpec => ({
  name: "Petrol",
  emoji: "⛽",
  unit: "L",
  perKm: lPer100 / 100,
  priceEur: "user",
  co2: 2.31,
  quip,
});
